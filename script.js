/* MUSIC PLAYER */

async function playMusic() {

    try {

        await backgroundMusic.play();

        musicIcon.textContent = "♫";

        musicLabel.textContent = translations[currentLanguage].musicOn;

    } catch (error) {

        showPopup(
            "Music",
            translations[currentLanguage].musicError,
            "♫"
        );

    }

}

function pauseMusic() {

    backgroundMusic.pause();

    musicIcon.textContent = "♪";

    musicLabel.textContent = translations[currentLanguage].musicOff;

}

musicButton.addEventListener("click", () => {

    if (backgroundMusic.paused) {

        playMusic();

    } else {

        pauseMusic();

    }

});

/* FALLING PETALS */

const petalContainer = document.getElementById("petalContainer");

const petalSymbols = ["♡", "✧", "✿", "·"];

function createPetal() {

    const petal = document.createElement("span");

    petal.classList.add("petal");

    petal.textContent = petalSymbols[
        Math.floor(Math.random() * petalSymbols.length)
    ];

    petal.style.left = Math.random() * 100 + "%";

    petal.style.fontSize = (10 + Math.random() * 15) + "px";

    petal.style.animationDuration = (8 + Math.random() * 10) + "s";

    petal.style.animationDelay = Math.random() * 5 + "s";

    petalContainer.appendChild(petal);

    setTimeout(() => {

        petal.remove();

    }, 20000);

}

for (let i = 0; i < 15; i++) {

    setTimeout(createPetal, i * 400);

}

setInterval(createPetal, 1200);

/* SCROLL REVEAL */

const revealObserver = new IntersectionObserver(entries => {

    entries.forEach(entry => {

        if (entry.isIntersecting) {

            entry.target.classList.add("visible");

            revealObserver.unobserve(entry.target);

        }

    });

}, {
    threshold: 0.12
});

document.querySelectorAll(".reveal").forEach(section => {

    revealObserver.observe(section);

});

