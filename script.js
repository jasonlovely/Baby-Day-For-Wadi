/* CHANGE LANGUAGE */

function changeLanguage(language) {
  currentLanguage = language;

  const content = translations[language];

  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (content[key]) {
      element.textContent = content[key];
    }
  });

  document.querySelectorAll(".letter-content p").forEach((paragraph, index) => {
    if (letterTranslations[language][index]) {
      paragraph.textContent = letterTranslations[language][index];
    }
  });

  if (backgroundMusic.paused) {
    musicLabel.textContent = content.musicOff;
  } else {
    musicLabel.textContent = content.musicOn;
  }

  if (currentPopupMessage) {
    popupMessage.textContent = content[currentPopupMessage] || "";
  }
}

/* LANGUAGE SELECTOR */

languageSelect.addEventListener("change", (event) => {
  changeLanguage(event.target.value);
});

/* POPUP FUNCTIONS */

function showPopup(title, message, icon = "♡") {
  popupTitle.textContent = title;
  popupMessage.textContent = message;
  popupIcon.textContent = icon;

  popupOverlay.classList.add("active");

  document.body.style.overflow = "hidden";
}

function closePopup() {
  popupOverlay.classList.remove("active");

  document.body.style.overflow = "";

  currentPopupMessage = "";
}

popupClose.addEventListener("click", closePopup);

popupOkay.addEventListener("click", closePopup);

popupOverlay.addEventListener("click", (event) => {
  if (event.target === popupOverlay) {
    closePopup();
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closePopup();
  }
});

